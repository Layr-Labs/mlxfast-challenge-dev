// MARK: - Dispatcher

/// Pick the right kernel for the given (head_dim, layer type).
private func gemma4FusedPickKernel(
    headDim: Int,
    isSliding: Bool
) -> MLXFast.MLXFastKernel {
    switch (headDim, isSliding) {
    case (256, true): return gemma4FusedSlidingQ  // head_dim is 256 for Q or K
    case (256, false): return gemma4FusedFullQ
    case (512, true): return gemma4FusedFullQ     // shouldn't happen — sliding is always D=256
    case (512, false): return gemma4FusedFullQ
    default:
        // Use full Q/K as a fallback — wrong shape will fail at runtime
        return headDim == 256 ? gemma4FusedSlidingK : gemma4FusedFullK
    }
}

/// Same kernel for Q and K (we'd ideally differentiate to keep the
/// specializations tight, but the kernel itself is head_dim-dispatched
/// and the Q/K specialization in the partial-RoPE kernel was only a
/// per-row_stride difference — fused kernels do not need per-role
/// constexprs since each row is one head).
///
/// Threadgroup geometry: one TG per row, threads = `head_dim_half`.
/// Grid: `[B*L*n_heads, 1, 1]`, threadGroup: `[head_dim_half, 1, 1]`.
public enum Gemma4FusedRMSNormRoPE {
    /// Apply fused RMSNorm + NEOX partial RoPE to a [B, L, n_heads,
    /// head_dim] contiguous tensor. Returns a new tensor of the same
    /// shape and layout. Pass `positions: [B*L]` (u32) for the
    /// per-row position; pass `eps: f32` for the RMS epsilon.
    public static func apply(
        x: MLXArray,
        weight: MLXArray,
        positions: MLXArray,
        eps: Float,
        headDim: Int,
        isSliding: Bool
    ) -> MLXArray {
        precondition(x.ndim == 4, "expected 4D input, got \(x.ndim)D")
        precondition(x.dtype == .bfloat16, "expected bf16 input, got \(x.dtype)")
        precondition(weight.ndim == 1, "expected 1D weight, got \(weight.ndim)D")
        precondition(weight.size == headDim, "weight size (\(weight.size)) must equal headDim (\(headDim))")
        precondition(x.shape[3] == headDim, "last dim (\(x.shape[3])) must equal headDim (\(headDim))")
        precondition(headDim == 256 || headDim == 512, "unsupported head_dim=\(headDim)")

        let B = x.shape[0]
        let L = x.shape[1]
        let nHeads = x.shape[2]
        let rows = B * L * nHeads

        // Flatten [B, L, n_heads, head_dim] -> [rows, head_dim] (no copy:
        // reshape is a view change for the contiguous tensor).
        let flat = x.reshaped([rows, headDim])

        let halfDimHalf: Int
        switch headDim {
        case 256: halfDimHalf = 128
        case 512: halfDimHalf = 256
        default: fatalError("unreachable")
        }

        let epsData = [eps]
        let epsBuf: MLXArray = epsData.withUnsafeBufferPointer { ptr in
            MLXArray(
                UnsafeRawBufferPointer(ptr),
                [1],
                type: Float.self
            )
        }

        let kernel = gemma4FusedPickKernel(headDim: headDim, isSliding: isSliding)

        return kernel(
            [flat, weight, positions, epsBuf],
            grid: (rows, halfDimHalf, 1),
            threadGroup: (halfDimHalf, 1, 1),
            outputShapes: [flat.shape],
            outputDTypes: [.bfloat16]
        )[0]
    }
}

/// Build a length-`length` u32 positions array `[start, start+1, …, start+length-1]`.
public func gemma4BuildFusedPositions(start: Int, length: Int) -> MLXArray {
    var data = [UInt32](repeating: 0, count: length)
    for i in 0..<length {
        data[i] = UInt32(start + i)
    }
    return data.withUnsafeBufferPointer { ptr in
        MLXArray(
            UnsafeRawBufferPointer(ptr),
            [length],
            type: UInt32.self
        )
    }
}
